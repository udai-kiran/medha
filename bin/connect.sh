#!/usr/bin/env bash
# Connect a Claude Code project to a running medha instance.
#
# Usage:
#   ./bin/connect.sh [TARGET_DIR]
#
# TARGET_DIR defaults to the current working directory.
# Idempotent — safe to re-run to change URL/project/secret.
#
# What this does:
#   1. Prompt for medha URL, secret, and project name
#   2. Write TARGET/.env.mcp  (picked up by hooks automatically)
#   3. Copy hooks + commands, wire settings.json  (via bin/install.sh)
#   4. Register the MCP server with 'claude mcp add'
#
# Skip prompts by setting env vars:
#   AGENTMEMORY_URL=http://192.168.2.91:3111 \
#   AGENTMEMORY_SECRET=abc123 \
#   AGENTMEMORY_PROJECT=myapp \
#   ./bin/connect.sh /path/to/your/project

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"

TARGET="${1:-$(pwd)}"
TARGET="$(cd "$TARGET" && pwd)"

ENV_MCP="$TARGET/.env.mcp"

# ── helpers ────────────────────────────────────────────────────────────────
if [ -t 1 ]; then
    C_BLUE='\033[0;34m'; C_GREEN='\033[0;32m'
    C_YELLOW='\033[0;33m'; C_RED='\033[0;31m'; C_RESET='\033[0m'
else
    C_BLUE=''; C_GREEN=''; C_YELLOW=''; C_RED=''; C_RESET=''
fi
info() { printf "${C_BLUE}•${C_RESET} %s\n" "$*"; }
ok()   { printf "${C_GREEN}✓${C_RESET} %s\n" "$*"; }
warn() { printf "${C_YELLOW}!${C_RESET} %s\n" "$*"; }
die()  { printf "${C_RED}ERROR:${C_RESET} %s\n" "$*" >&2; exit 1; }

command -v jq >/dev/null 2>&1 || die "jq is required but not found"

# Prompt helper: uses env var if set, otherwise reads from tty with a default.
ask() {
    local var="$1" prompt="$2" default="${3:-}"
    if [ -n "${!var:-}" ]; then
        printf '  %s: %s (from env)\n' "$prompt" "${!var}" >&2
        printf '%s' "${!var}"; return
    fi
    if [ -n "$default" ]; then printf '  %s [%s]: ' "$prompt" "$default" >&2
    else printf '  %s: ' "$prompt" >&2; fi
    IFS= read -r _v </dev/tty
    printf '%s' "${_v:-$default}"
}

# ── 0. load existing .env.mcp as defaults (idempotent re-runs) ─────────────
if [ -f "$ENV_MCP" ]; then
    [ -z "${AGENTMEMORY_URL:-}" ]     && AGENTMEMORY_URL=$(grep     '^AGENTMEMORY_URL='     "$ENV_MCP" 2>/dev/null | cut -d= -f2- || true)
    [ -z "${AGENTMEMORY_SECRET:-}" ]  && AGENTMEMORY_SECRET=$(grep  '^AGENTMEMORY_SECRET='  "$ENV_MCP" 2>/dev/null | cut -d= -f2- || true)
    [ -z "${AGENTMEMORY_PROJECT:-}" ] && AGENTMEMORY_PROJECT=$(grep '^AGENTMEMORY_PROJECT=' "$ENV_MCP" 2>/dev/null | cut -d= -f2- || true)
fi

# ── 1. collect config ──────────────────────────────────────────────────────
echo ""
info "Connecting $TARGET to medha"
echo ""

AGENTMEMORY_URL=$(ask AGENTMEMORY_URL "medha API URL" "http://localhost:3111")

AGENTMEMORY_SECRET=$(ask AGENTMEMORY_SECRET "medha secret (blank if auth is off)" "")

# Default project name: basename of the target directory.
# Users can set AGENTMEMORY_PROJECT to skip the prompt entirely.
_DEFAULT_PROJECT=$(basename "$TARGET")
AGENTMEMORY_PROJECT=$(ask AGENTMEMORY_PROJECT "Project name in medha" "$_DEFAULT_PROJECT")

# Derive MCP URL: same host as API, port 3114.
_API_HOST=$(printf '%s' "$AGENTMEMORY_URL" | sed 's|:[0-9]*$||')
MCP_URL="${_API_HOST}:3114/mcp"

echo ""
info "  API     → $AGENTMEMORY_URL"
info "  MCP     → $MCP_URL"
info "  Project → $AGENTMEMORY_PROJECT"
echo ""

# ── 2. write .env.mcp ─────────────────────────────────────────────────────
info "Writing $ENV_MCP"
cat > "$ENV_MCP" <<ENVMCP
# medha hook config — generated by bin/connect.sh
# Hooks (agentmem-*) read these vars when firing. Keep out of version control
# if AGENTMEMORY_SECRET is non-empty.
AGENTMEMORY_URL=$AGENTMEMORY_URL
AGENTMEMORY_SECRET=$AGENTMEMORY_SECRET
AGENTMEMORY_PROJECT=$AGENTMEMORY_PROJECT
ENVMCP
ok ".env.mcp written"

# ── 3. copy hooks, commands, wire settings.json ───────────────────────────
"$SCRIPT_DIR/install.sh" "$TARGET"

# ── 4. register MCP server ────────────────────────────────────────────────
if command -v claude >/dev/null 2>&1; then
    info "Registering MCP server…"
    claude mcp remove agent-mem 2>/dev/null || true
    claude mcp add agent-mem --transport http "$MCP_URL"
    ok "MCP registered"
else
    warn "'claude' CLI not found — skipping MCP registration"
    printf '  Run manually: claude mcp add agent-mem --transport http %s\n' "$MCP_URL"
fi

# ── done ──────────────────────────────────────────────────────────────────
echo ""
printf "${C_GREEN}medha connected.${C_RESET}\n\n"
printf '  Project: %s\n' "$AGENTMEMORY_PROJECT"
printf '  API:     %s\n' "$AGENTMEMORY_URL"
printf '  MCP:     %s\n' "$MCP_URL"
echo ""
echo "Restart Claude Code in that directory to activate the hooks."
